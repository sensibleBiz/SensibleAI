const vector768 = customType<{ data: number[]; driverData: string }>({
  dataType: () => "vector(768)",
  toDriver: (value) => JSON.stringify(value),
  fromDriver: (value) => value.replace(/^\[|\]$/g, "").split(",").map(Number),
});
const tsvector = customType<{ data: string; driverData: string }>({ dataType: () => "tsvector" });

